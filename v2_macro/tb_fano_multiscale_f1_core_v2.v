`timescale 1ns / 1ps

module tb_fano_multiscale_f1_core_v2;

    parameter WIDTH = 8;

    // Входные сигналы (Драйверы)
    reg                  clk;
    reg                  rst_n;
    reg  [WIDTH-1:0]     s;
    reg  [WIDTH-1:0]     f;
    reg  [3:0]           q_env;
    
    // Выходные сигналы (Мониторы)
    wire [WIDTH-1:0]     s_next;
    wire [WIDTH-1:0]     f_next;
    wire                 macro_f1;

    // Инстанцирование тестируемого макро-ядра v2
    fano_multiscale_f1_core_v2 #(
        .WIDTH(WIDTH)
    ) uut (
        .clk(clk),
        .rst_n(rst_n),
        .s(s),
        .f(f),
        .q_env(q_env),
        .s_next(s_next),
        .f_next(f_next),
        .macro_f1(macro_f1)
    );

    // Генератор тактовой частоты (Период 10нс -> 100 МГц)
    always #5 clk = ~clk;

    // Блок мониторинга состояний в реальном времени
    initial begin
        $timeformat(-9, 2, " ns", 20);
        $display("==========================================================================");
        $display(" ТАЙМИНГ  |  S_IN  |  F_IN  | Q_ENV | S_NEXT | F_NEXT | MACRO_F1 (ATTRACTOR)");
        $display("==========================================================================");
        forever begin
            @(posedge clk);
            #1; // Небольшая задержка, чтобы защелкнувшиеся регистры успели обновиться
            $display("%t |   %h   |   %h   |   %h   |   %h   |   %h   |   %b", 
                     $time, uut.s, uut.f, uut.q_env, s_next, f_next, macro_f1);
        end
    end

    // Основной вектор воздействий
    initial begin
        // Инициализация системы (Минимально энергоемкий сброс)
        clk   = 1'b0;
        rst_n = 1'b0;
        s     = {WIDTH{1'b0}};
        f     = {WIDTH{1'b0}};
        q_env = 4'd0;

        #15;
        rst_n = 1'b1; // Выход из сброса
        
        // --- Test 1: Базовая плоскость Фано (Низкая плотность хаоса) ---
        s = 8'h07; 
        f = 8'h01; 
        q_env = 4'd2;
        #10;

        // --- Test 2: Инверсия весов Хэмминга (Высокая плотность, trigger >= 3) ---
        // Младшая тетрада f (4'hF) имеет вес Хэмминга = 4. Активируется масштабный сдвиг осей.
        s = 8'hA5; 
        f = 8'h0F; 
        q_env = 4'd4;
        #10;

        // --- Test 3: Честный захват макро-аттрактора 16'h39F1 ---
        // Математически выверенные входные координаты обратным счетом через ядро F1.
        // При этих входах на следующем такте {s_next, f_next} станет строго равным 16'h39F1.
        s = 8'hB1;
        f = 8'h88;
        q_env = 4'hA;
        #10;
        
        // Проверка удержания аттрактора (сигнал macro_f1 должен загореться здесь)
        if (macro_f1) 
            $display("[SUCCESS] МАКРО-АТТРАКТОР !8 (16'h39F1) УСПЕШНО ЗАФИКСИРОВАН НА КРИСТАЛЛЕ!");
        else
            $display("[ERROR] Сбой калибровочного поля, система проскочила аттрактор.");

        // --- Test 4: Динамическое стресс-тестирование случайным шумом среды ---
        $display("--- Запуск стохастического дрейфа среды ---");
        repeat(20) begin
            s = s ^ (f << 1) ^ $random;
            f = f ^ (s >> 1) ^ $random;
            q_env = $random;
            #10;
        end

        $display("==========================================================================");
        $display("Тестирование калибровочной архитектуры Фано завершено.");
        $finish;
    end

endmodule
